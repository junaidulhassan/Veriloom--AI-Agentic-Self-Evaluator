import { useMemo, useState } from 'react'
import { motion } from 'framer-motion'
import {
  Area,
  AreaChart,
  Bar,
  BarChart,
  CartesianGrid,
  Legend,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts'
import { ArrowDownToLine, ArrowUpFromLine, Coins, Divide } from 'lucide-react'
import { ChartCard } from '@/components/charts/ChartCard'
import { ChartTooltip } from '@/components/charts/ChartTooltip'
import { axisProps, cursorStyle, gridProps, legendProps, lineCursor } from '@/components/charts/theme'
import { SegmentedControl } from '@/components/ui/SegmentedControl'
import { StatCard } from '@/components/ui/StatCard'
import { getToolConfig } from '@/features/tools/registry'
import { formatNumber, titleCase, truncate } from '@/lib/format'
import { stagger } from '@/lib/motion'
import type { TokenGroupBy, TokenGroupRow } from '@/types/api'
import { useTokenBreakdown, useTokens } from '../hooks'
import { Section } from '../components/Section'
import { dayTick, useChartAnimation } from '../components/chartHelpers'

const groupOptions: { value: TokenGroupBy; label: string }[] = [
  { value: 'session', label: 'Session' },
  { value: 'request', label: 'Request' },
  { value: 'tool', label: 'Tool' },
  { value: 'component', label: 'Agent step' },
]

function label(row: TokenGroupRow, groupBy: TokenGroupBy) {
  if (groupBy === 'tool') return row.key ? getToolConfig(row.key).shortLabel : 'No tool'
  if (groupBy === 'component') return titleCase(row.key ?? 'unknown')
  return truncate(row.label ?? row.key ?? 'unknown', 28)
}

export default function TokensSection() {
  const tokens = useTokens()
  const [groupBy, setGroupBy] = useState<TokenGroupBy>('session')
  const breakdown = useTokenBreakdown(groupBy, 12)
  const anim = useChartAnimation()
  const t = tokens.data
  const daily = useMemo(
    () =>
      (t?.by_day ?? []).map((d) => ({ date: d.key ?? '', Input: d.input_tokens, Output: d.output_tokens })),
    [t],
  )
  const grouped = useMemo(
    () =>
      (breakdown.data ?? []).map((row) => ({
        name: label(row, groupBy),
        Input: row.input_tokens,
        Output: row.output_tokens,
        total: row.total_tokens,
      })),
    [breakdown.data, groupBy],
  )

  return (
    <Section id="tokens" description="Token consumption by day, session, request and tool.">
      <motion.div variants={stagger(0.05)} className="grid grid-cols-1 gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard
          label="Total tokens"
          value={t?.total_tokens}
          format={(v) => formatNumber(v, { compact: true })}
          icon={<Coins className="size-4" />}
          loading={tokens.isPending}
          hint={t ? `${formatNumber(t.llm_calls)} LLM calls` : undefined}
          info="All input and output tokens recorded for agent, finalize and evaluator calls."
          spark={daily.map((d) => d.Input + d.Output)}
        />
        <StatCard
          label="Input tokens"
          value={t?.total_input_tokens}
          format={(v) => formatNumber(v, { compact: true })}
          icon={<ArrowUpFromLine className="size-4" />}
          loading={tokens.isPending}
          info="Prompt tokens sent to the language model, including history and tool results."
          spark={daily.map((d) => d.Input)}
          sparkColor="var(--series-2)"
        />
        <StatCard
          label="Output tokens"
          value={t?.total_output_tokens}
          format={(v) => formatNumber(v, { compact: true })}
          icon={<ArrowDownToLine className="size-4" />}
          loading={tokens.isPending}
          info="Completion tokens generated by the language model."
          spark={daily.map((d) => d.Output)}
          sparkColor="var(--series-1)"
        />
        <StatCard
          label="Avg per request"
          value={t?.avg_tokens_per_request}
          format={(v) => formatNumber(v)}
          icon={<Divide className="size-4" />}
          loading={tokens.isPending}
          hint={t ? `${formatNumber(t.avg_tokens_per_llm_call)} per LLM call` : undefined}
          info="Mean tokens consumed per agent request."
        />
      </motion.div>
      <div className="grid grid-cols-1 gap-4 xl:grid-cols-2">
        <ChartCard
          title="Tokens over time"
          info="Daily input and output tokens stacked; the top edge is the day's total."
          loading={tokens.isPending}
          error={tokens.error}
          onRetry={() => tokens.refetch()}
          empty={!daily.length}
          csv={() => daily}
          height={280}
        >
          <ResponsiveContainer width="100%" height={280}>
            <AreaChart data={daily} margin={{ top: 8, right: 8, left: 0, bottom: 0 }}>
              <CartesianGrid {...gridProps} />
              <XAxis dataKey="date" {...axisProps} tickFormatter={dayTick} minTickGap={24} />
              <YAxis {...axisProps} width={52} tickFormatter={(v) => formatNumber(v, { compact: true })} />
              <Tooltip
                cursor={lineCursor}
                content={
                  <ChartTooltip
                    labelFormatter={(l) => dayTick(String(l))}
                    formatter={(v) => formatNumber(v)}
                  />
                }
              />
              <Legend {...legendProps} />
              <Area
                type="monotone"
                dataKey="Input"
                stackId="t"
                stroke="var(--series-2)"
                fill="var(--series-2)"
                fillOpacity={0.25}
                strokeWidth={2}
                {...anim}
              />
              <Area
                type="monotone"
                dataKey="Output"
                stackId="t"
                stroke="var(--series-1)"
                fill="var(--series-1)"
                fillOpacity={0.25}
                strokeWidth={2}
                {...anim}
              />
            </AreaChart>
          </ResponsiveContainer>
        </ChartCard>
        <ChartCard
          title="Top token consumers"
          info="The heaviest sessions, requests, tools or agent steps by total tokens, split into input and output."
          loading={breakdown.isPending}
          error={breakdown.error}
          onRetry={() => breakdown.refetch()}
          empty={!grouped.length}
          csv={() => grouped}
          height={280}
          actions={
            <SegmentedControl<TokenGroupBy>
              size="sm"
              label="Group tokens by"
              value={groupBy}
              onChange={setGroupBy}
              options={groupOptions}
              className="mr-1 hidden sm:inline-flex"
            />
          }
        >
          <ResponsiveContainer width="100%" height={280}>
            <BarChart
              data={grouped}
              layout="vertical"
              margin={{ top: 4, right: 16, left: 8, bottom: 0 }}
              barCategoryGap="20%"
            >
              <CartesianGrid {...gridProps} horizontal={false} vertical />
              <XAxis type="number" {...axisProps} tickFormatter={(v) => formatNumber(v, { compact: true })} />
              <YAxis type="category" dataKey="name" {...axisProps} width={140} interval={0} />
              <Tooltip cursor={cursorStyle} content={<ChartTooltip formatter={(v) => formatNumber(v)} />} />
              <Legend {...legendProps} />
              <Bar
                dataKey="Input"
                stackId="g"
                fill="var(--series-2)"
                stroke="var(--chart-surface)"
                strokeWidth={2}
                {...anim}
              />
              <Bar
                dataKey="Output"
                stackId="g"
                fill="var(--series-1)"
                stroke="var(--chart-surface)"
                strokeWidth={2}
                radius={[0, 4, 4, 0]}
                {...anim}
              />
            </BarChart>
          </ResponsiveContainer>
        </ChartCard>
      </div>
    </Section>
  )
}
